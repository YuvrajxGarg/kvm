KEYS = {}        # hid -> (name, mac, win_scan, win_vk)
BY_NAME = {}     # name -> hid
_MAC = {}        # mac keycode -> hid
_WIN = {}        # win scan (with 0xE000 for extended) -> hid
_WIN_VK = {}     # win virtual-key -> hid (for keys that come without a useful scan code)

for row in _TABLE:
    name, hid, mac, scan = row[:4]
    vk = row[4] if len(row) > 4 else None
    KEYS[hid] = (name, mac, scan, vk)
    BY_NAME[name] = hid
    if mac is not None:
        _MAC.setdefault(mac, hid)
    _WIN.setdefault(scan, hid)
    if vk is not None:
        _WIN_VK[vk] = hid
# The Mac's keypad Clear sits where Num Lock is; Help is the old Insert.
_MAC[0x47] = BY_NAME["numlock"]

MODIFIERS = {BY_NAME[n] for n in ("lctrl", "lshift", "lalt", "lmeta", "rctrl", "rshift", "ralt", "rmeta")}
CTRL = {BY_NAME["lctrl"], BY_NAME["rctrl"]}
ALT = {BY_NAME["lalt"], BY_NAME["ralt"]}
META = {BY_NAME["lmeta"], BY_NAME["rmeta"]}
SHIFT = {BY_NAME["lshift"], BY_NAME["rshift"]}

# Command <-> Control, so Cmd+C on the Mac is Ctrl+C on the PC (and the other way round).
SWAP_CMD_CTRL = {
    BY_NAME["lmeta"]: BY_NAME["lctrl"], BY_NAME["lctrl"]: BY_NAME["lmeta"],
    BY_NAME["rmeta"]: BY_NAME["rctrl"], BY_NAME["rctrl"]: BY_NAME["rmeta"],
}

# Mac modifier keycodes and the device-dependent flag bit that says each one is down.
MAC_MOD_BITS = {0x3B: 0x01, 0x38: 0x02, 0x3C: 0x04, 0x37: 0x08, 0x36: 0x10, 0x3A: 0x20, 0x3D: 0x40, 0x3E: 0x2000}


def from_mac(keycode):
    return _MAC.get(keycode)


def to_mac(hid):
    k = KEYS.get(hid)
    return k[1] if k else None


def from_win(scan, extended, vk=None):
    """A key from Windows' low-level hook: scan code, the extended flag and the virtual-key."""
    if vk in _WIN_VK and vk in (0x13, 0x90, 0xAD, 0xAE, 0xAF, 0xB0, 0xB1, 0xB2, 0xB3):
        return _WIN_VK[vk]
    code = (0xE000 | scan) if extended else scan
    hid = _WIN.get(code)
    if hid is None and extended:
        hid = _WIN.get(scan)  # some keyboards flag Right Shift as extended
    return hid


def to_win(hid):
    """(scan, extended, vk) to inject on Windows, or None."""
    k = KEYS.get(hid)
    if not k:
        return None
    scan = k[2]
    return (scan & 0xFF, bool(scan & 0xE000), k[3])


def name(hid):
    k = KEYS.get(hid)
    return k[0] if k else "0x%02x" % hid


def parse_combo(text):
    """'ctrl+alt+esc' -> list of alternatives, each a set of hids (ctrl means either side)."""
    groups = []
    for part in (text or "").lower().replace(" ", "").split("+"):
        if not part:
            continue
        if part in ("ctrl", "control"):
            groups.append(CTRL)
        elif part in ("alt", "option", "opt"):
            groups.append(ALT)
        elif part in ("cmd", "command", "win", "meta", "super"):
            groups.append(META)
        elif part == "shift":
            groups.append(SHIFT)
        elif part in BY_NAME:
            groups.append({BY_NAME[part]})
    return groups


def combo_down(groups, held):
    return bool(groups) and all(held & g for g in groups)
